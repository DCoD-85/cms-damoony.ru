<?php

declare(strict_types=1);

namespace Damoony\Cli\Db\Commands;

use Damoony\Cli\CommandInterface;
use Damoony\Cli\Context;
use Damoony\Cli\Result;
use Damoony\Core\Files\Paths;
use Damoony\Core\Config;

final class SchemaGenerateSqlCommand implements CommandInterface
{
    public function __construct(
        private readonly Paths $paths,
        private readonly Config $site,
    ) {
    }

    public function name(): string
    {
        return 'db:schema:generate-sql';
    }

    public function description(): string
    {
        return 'Generate SQL migration from schema.json';
    }

    public function run(array $args, Context $context): Result
    {
        $r = new Result();
        
        $domain = (string) ($args['domain'] ?? '');
        if ($domain === '' || str_contains($domain, '..')) {
            $r->error('Invalid or missing --domain');
            return $r;
        }

        $schemaFile = $this->paths->domain($domain) . '/.db/schema.json';
        if (!is_file($schemaFile)) {
            $r->error('schema.json not found.');
            return $r;
        }

        $schema = json_decode((string)file_get_contents($schemaFile), true);
        if (!isset($schema['tables']) || !is_array($schema['tables'])) {
            $r->error('Invalid schema.json format.');
            return $r;
        }

        // Получаем префикс из конфига
        $prefix = '';
        $map = $this->site->getByKey(['domains_aliases_storage', $domain, 'www', 'prefix'], '');
        if (is_string($map)) $prefix = $map;

        $sql = "-- Generated by dbcli for domain: {$domain}\n";
        $sql .= "-- Date: " . date('Y-m-d H:i:s') . "\n\n";

        foreach ($schema['tables'] as $tableName => $tableData) {
            $physicalTable = $prefix . $tableName;
            $sql .= "CREATE TABLE IF NOT EXISTS `{$physicalTable}` (\n";
            
            $cols = [];
            foreach ($tableData['columns'] as $colName => $colDef) {
                $line = "    `{$colName}` ";
                
                switch ($colDef['type']) {
                    case 'int': $line .= "INT"; break;
                    case 'varchar': $line .= "VARCHAR(" . ($colDef['length'] ?? 255) . ")"; break;
                    case 'text': $line .= "TEXT"; break;
                    case 'timestamp': $line .= "TIMESTAMP"; break;
                    case 'boolean': $line .= "TINYINT(1)"; break;
                    case 'decimal': $line .= "DECIMAL(10,2)"; break;
                    default: $line .= "VARCHAR(255)";
                }

                if (!empty($colDef['primary'])) $line .= " PRIMARY KEY";
                if (!empty($colDef['auto_increment'])) $line .= " AUTO_INCREMENT";
                
                if (isset($colDef['null']) && $colDef['null'] === true) {
                    $line .= " NULL";
                } else if (empty($colDef['primary'])) {
                    $line .= " NOT NULL";
                }

                if (isset($colDef['default'])) {
                    $def = $colDef['default'];
                    if ($def === 'CURRENT_TIMESTAMP') {
                        $line .= " DEFAULT CURRENT_TIMESTAMP";
                    } elseif (is_string($def)) {
                        $line .= " DEFAULT '" . addslashes($def) . "'";
                    } elseif (is_bool($def)) {
                        $line .= " DEFAULT " . ($def ? '1' : '0');
                    } else {
                        $line .= " DEFAULT " . $def;
                    }
                }
                
                $cols[] = $line;
            }
            
            $sql .= implode(",\n", $cols) . "\n";
            $sql .= ") ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;\n\n";
        }

        // Сохраняем в папку migrations
        $migrationsDir = $this->paths->root() . '/migrations';
        if (!is_dir($migrationsDir)) {
            mkdir($migrationsDir, 0o775, true);
        }
        
        $filename = 'gen_' . date('Ymd_His') . '_' . str_replace('.', '_', $domain) . '.sql';
        $filepath = $migrationsDir . '/' . $filename;
        
        file_put_contents($filepath, $sql);
        
        $r->file('migrations/' . $filename);
        $context->step("Migration generated: {$filename}", true);
        $context->step("To apply, run: php bin/cli.php db:migrate", true);

        return $r;
    }
}
