<?php

declare(strict_types=1);

namespace Damoony\Cli\Commands;

use Damoony\Cli\CommandInterface;
use Damoony\Cli\Context;
use Damoony\Cli\Result;
use Damoony\Core\Files\Fs;
use Damoony\Core\Files\Paths;
use Damoony\UI\Attrs;
use Damoony\UI\Builder;
use Damoony\UI\Element;
use Damoony\UI\Text;

final class ApiReflectCommand implements CommandInterface
{
    public function __construct(private readonly Paths $paths)
    {
    }

    public function name(): string
    {
        return 'api:reflect';
    }

    public function description(): string
    {
        return 'Сгенерировать стабы для IDE (Builder, Element, Attrs)';
    }

    public function run(array $args, Context $context): Result
    {
        $r = new Result();
        $classes = [
            Builder::class,
            Element::class,
            Attrs::class,
            Text::class,
        ];

        $stub = "<?php\n\n";
        $stub .= "// AUTO-GENERATED by `php bin/cli.php api:reflect`\n";
        $stub .= "// This file is for IDE autocompletion only. Do not include it in production.\n\n";

        foreach ($classes as $className) {
            $ref = new \ReflectionClass($className);
            $shortName = $ref->getShortName();
            $stub .= "namespace Damoony\UI\IDE;

";
            $stub .= "class {$shortName}Stub {
";

            foreach ($ref->getMethods(\ReflectionMethod::IS_PUBLIC) as $method) {
                if ($method->getDeclaringClass()->getName() !== $className) {
                    continue;
                }
                $params = [];
                foreach ($method->getParameters() as $param) {
                    $type = $param->hasType() ? $param->getType() . ' ' : '';
                    $default = $param->isDefaultValueAvailable() ? ' = ' . var_export($param->getDefaultValue(), true) : '';
                    $params[] = $type . '$' . $param->getName() . $default;
                }
                $return = $method->hasReturnType() ? ': ' . $method->getReturnType() : '';
                $stub .= "    public static function {$method->getName()}(" . implode(', ', $params) . ") {$return} {}
";
            }
            $stub .= "}\n\n";
        }

        $stubFile = $this->paths->root() . '/_dev/api.stub.php';
        Fs::writeAtomic($stubFile, $stub);

        $r->step('Стабы сгенерированы: ' . Fs::rel($stubFile, $this->paths->root()));
        return $r;
    }
}
