<?php

declare(strict_types=1);

namespace Damoony\Cli\Commands;

use Damoony\Cli\CommandInterface;
use Damoony\Cli\Context;
use Damoony\Cli\Result;
use Damoony\Core\Files\Fs;
use Damoony\Core\Files\Paths;
use Damoony\UI\Attrs;
use Damoony\UI\Builder;
use Damoony\UI\Element;
use Damoony\UI\Text;
use ReflectionClass;
use ReflectionMethod;
use ReflectionNamedType;

/**
 * api:reflect — стабы Builder/Element/Attrs/Text для IDE-автодополнения.
 */
final class ApiReflectCommand implements CommandInterface
{
    private const CLASSES = [Builder::class, Element::class, Attrs::class, Text::class];

    public function __construct(private readonly Paths $paths)
    {
    }

    public function name(): string
    {
        return 'api:reflect';
    }

    public function description(): string
    {
        return 'Сгенерировать стабы для IDE (Builder, Element, Attrs, Text)';
    }

    public function run(array $args, Context $context): Result
    {
        $r = new Result();

        $stub = "<?php\n\n"
            . "// AUTO-GENERATED by `php bin/cli.php api:reflect`\n"
            . "// Только для автодополнения в IDE. Не подключать в production.\n\n";

        foreach (self::CLASSES as $className) {
            /** @var class-string $className */
            $stub .= $this->classStub($className);
        }

        $file = $this->paths->root() . '/_dev/api.stub.php';

        if ($context->isDryRun()) {
            $context->step('Dry-run: стабы будут записаны в ' . Fs::rel($file, $this->paths->root()));
            $r->data = ['file' => Fs::rel($file, $this->paths->root()), 'dry_run' => true];

            return $r;
        }

        Fs::writeAtomic($file, $stub);
        $r->file(Fs::rel($file, $this->paths->root()));

        $r->data = ['file' => Fs::rel($file, $this->paths->root())];
        $context->step('Стабы сгенерированы', true, Fs::rel($file, $this->paths->root()));

        return $r;
    }

    /**
     * @param class-string $className
     */
    private function classStub(string $className): string
    {
        $ref = new ReflectionClass($className);
        $short = $ref->getShortName();

        $code = "namespace Damoony\\UI\\IDE;\n\nclass {$short}Stub\n{\n";

        foreach ($ref->getMethods(ReflectionMethod::IS_PUBLIC) as $method) {
            if ($method->getDeclaringClass()->getName() !== $className) {
                continue;
            }

            $params = [];
            foreach ($method->getParameters() as $parameter) {
                $type = $parameter->hasType() ? $parameter->getType() . ' ' : '';
                $default = $parameter->isDefaultValueAvailable()
                    ? ' = ' . var_export($parameter->getDefaultValue(), true)
                    : '';
                $params[] = $type . '$' . $parameter->getName() . $default;
            }

            $returnType = $method->getReturnType();
            $return = $returnType === null ? '' : ': ' . $this->typeToString($returnType);

            $code .= sprintf(
                "    public static function %s(%s)%s {}\n",
                $method->getName(),
                implode(', ', $params),
                $return,
            );
        }

        return $code . "}\n\n";
    }

    private function typeToString(\ReflectionType $type): string
    {
        if ($type instanceof ReflectionNamedType) {
            return $type->getName();
        }

        return (string) $type;
    }
}
